  private void addbrand(){
     String brandName = brandInput.getText();
       logger.info("Attempting to add brand: " + brandName);

        
        try {
            ResultSet rs = Mysql.excute("SELECT `bid` FROM `brand` WHERE `brand`.`name` = '" + brandName + "'");
            if (rs.next()) {
                JOptionPane.showMessageDialog(null,
                        "This brand is already exists ",
                        "brand information dialog",
                        JOptionPane.ERROR_MESSAGE);
                 logger.warning("Brand already exists: " + brandName);
            }else{
            Mysql.excute("INSERT INTO `brand`(`name`)"
                    + "VALUES('" + brandName + "')");
            
            JOptionPane.showMessageDialog(null, 
                    "New brand addedd succesfully ",
                    "brand information dialog",
           JOptionPane.INFORMATION_MESSAGE );
             logger.info("New brand added successfully: " + brandName);
        this.dispose();
            
            
            }
        } catch (SQLException e) {
            logger.severe("SQLException when adding brand '" + brandName + "': " + e.getMessage());
            e.printStackTrace();
            this.dispose();
        }
  }

    
